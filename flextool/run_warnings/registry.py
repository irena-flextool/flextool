#: ``{code: spec}`` of every code in use, in code order.
WARNINGS: dict[str, WarningSpec] = {spec.code: spec for spec in _SPECS}

#: Codes that were used once and are retired: never give them to a new warning (old logs still name them).
RETIRED: frozenset[str] = frozenset()


def docs_url(code: str) -> str:
    """The documentation of *code* (``W-0123`` → ``<WARNINGS_DOCS_URL>#w-0123``)."""
    return f"{WARNINGS_DOCS_URL}#{code.lower()}"
